export function verdictLabelFor(lang, v) {
  if (lang !== 'en' && VERDICT_LABELS[v] && VERDICT_LABELS[v][lang]) return VERDICT_LABELS[v][lang]
  return { dry: 'Dry', light_rain: 'Light rain', rain: 'Rain', heavy_rain: 'Heavy rain', thunderstorm: 'Thunderstorm', snow: 'Snow' }[v] || v || '—'
}

export function purposeLabelFor(lang, p) {
  if (lang !== 'en' && PURPOSE_LABELS[p] && PURPOSE_LABELS[p][lang]) return PURPOSE_LABELS[p][lang]
  return p
}

export function metricLabelFor(lang, m) {
  if (lang !== 'en' && METRIC_LABELS[m] && METRIC_LABELS[m][lang]) return METRIC_LABELS[m][lang]
  return (METRIC_LABELS[m] && METRIC_LABELS[m].en) || m
}
